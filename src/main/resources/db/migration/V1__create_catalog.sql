CREATE TABLE businesses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_account_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    address VARCHAR(255) NOT NULL,
    district VARCHAR(100) NOT NULL,
    latitude DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    contact_phone VARCHAR(30) NOT NULL,
    pickup_conditions TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    plus_partner BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE offers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL REFERENCES businesses(id),
    category VARCHAR(80) NOT NULL,
    title VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,
    allergens TEXT NOT NULL DEFAULT '',
    original_price NUMERIC(10, 2) NOT NULL CHECK (original_price > 0),
    offer_price NUMERIC(10, 2) NOT NULL CHECK (offer_price > 0 AND offer_price < original_price),
    initial_units INTEGER NOT NULL CHECK (initial_units > 0),
    available_units INTEGER NOT NULL CHECK (available_units BETWEEN 0 AND initial_units),
    pickup_start_at TIMESTAMP WITH TIME ZONE NOT NULL,
    pickup_end_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'PAUSED', 'EXPIRED')),
    image_url VARCHAR(2048) NOT NULL DEFAULT '',
    plus_exclusive BOOLEAN NOT NULL DEFAULT FALSE,
    CHECK (pickup_start_at < pickup_end_at),
    CHECK (expires_at <= pickup_end_at)
);

CREATE INDEX ix_businesses_district ON businesses(district);
CREATE INDEX ix_offers_business_id ON offers(business_id);
CREATE INDEX ix_offers_catalog ON offers(status, category, expires_at);

CREATE TABLE reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    offer_id BIGINT NOT NULL REFERENCES offers(id),
    business_id BIGINT NOT NULL REFERENCES businesses(id),
    customer_user_id BIGINT NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(10, 2) NOT NULL,
    original_unit_price NUMERIC(10, 2) NOT NULL,
    pickup_code VARCHAR(32) NOT NULL UNIQUE,
    pickup_start_at TIMESTAMP WITH TIME ZONE NOT NULL,
    pickup_deadline_at TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(30) NOT NULL CHECK (status IN ('ACTIVE', 'COLLECTED', 'CANCELLED', 'EXPIRED')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    collected_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX ix_reservations_customer ON reservations(customer_user_id, created_at);
CREATE INDEX ix_reservations_offer ON reservations(offer_id, status);
